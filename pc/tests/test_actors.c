    for(unsigned c=0;c<6;++c)animation_bytes[12+c*4]=1;
    PeAnimation animation;char animation_error[128];
    CHECK(pe_animation_open(animation_bytes,sizeof(animation_bytes),&animation,animation_error,sizeof(animation_error)));
    PeActor *animated=&actors->slots[0];animated->animation_clock.stop=2;
    CHECK(pe_actor_set_animation(animated,&animation,7,0));
    CHECK(animated->action==7&&animated->animation_clock.last==2&&animated->animation_clock.stop==2);
    CHECK(pe_actor_advance_animation(animated)&&animated->animation_clock.frame==0x10000);
    animated->script.flags|=0x200;
    CHECK(pe_actor_set_animation(animated,&animation,7,0)&&animated->animation_clock.frame==0x10000&&!(animated->script.flags&0x200));
    CHECK(pe_actor_set_animation(animated,&animation,7,1)&&!animated->animation_clock.frame);
    CHECK(pe_actor_advance_animation(animated));
    CHECK(pe_actor_set_animation(animated,&animation,8,0)&&!animated->animation_clock.frame);
    animation.frames=0;CHECK(!pe_actor_set_animation(animated,&animation,9,1)&&animated->action==8);
    CHECK(pe_actors_spawn(actors, 2, 0, -1, 0, 0, 0) < 0 && actors->live == 3 && banks.actor_serial == 4);
    while (actors->live < PE_ACTOR_CAPACITY) CHECK(pe_actors_spawn(actors, 1, 0, -1, 0, 0, 0) >= 0);
    CHECK(pe_actors_spawn(actors, 1, 0, -1, 0, 0, 0) < 0 && actors->live == PE_ACTOR_CAPACITY);
    CHECK(scheduler->live == PE_ACTOR_CAPACITY && banks.actor_serial == PE_ACTOR_CAPACITY + 1);
    CHECK(pe_script_scheduler_tick(scheduler, &actors->slots[0].script, 100));
    CHECK(pe_script_scheduler_collect(scheduler, &actors->slots[0].script));
    for (unsigned i = 1; i < PE_ACTOR_CAPACITY; ++i) {
        CHECK(pe_script_scheduler_tick(scheduler, &actors->slots[i].script, 100));
        CHECK(pe_script_scheduler_collect(scheduler, &actors->slots[i].script));
    }
    CHECK(!scheduler->live);
    pe_script_scheduler_init(scheduler, &program, &banks); pe_actors_init(actors, scheduler);
    PeScriptActor dummy; pe_script_actor_init(&dummy, 32);
    for (unsigned i = 0; i < PE_SCRIPT_TASK_CAPACITY; ++i)
        CHECK(pe_script_scheduler_start(scheduler, &dummy, 2, 32) >= 0);
    CHECK(pe_actors_spawn(actors, 0, 0, -1, 0, 0, 0) < 0);
    CHECK(!actors->live && actors->head == -1 && actors->player == -1 && actors->free_head == 0);
    CHECK(banks.actor_serial == 1 && scheduler->live == PE_SCRIPT_TASK_CAPACITY);
    pe_script_scheduler_init(scheduler, &program, &banks); pe_actors_init(actors, scheduler);
    CHECK(pe_actors_spawn(actors, 1, 0, -1, 0, 0, 0) == 0);
    CHECK(pe_actors_spawn(actors, 0, 0, 0, 0, 0, 0) == 1);
    CHECK(pe_actors_spawn(actors, 1, 0, 1, 0, 0, 0) == 2);
    banks.move_lock = UINT32_MAX;
    actors->slots[1].script.flags |= 0x10;
    actors->slots[0].script.flags |= 0x800000;
    CHECK(actors->live == 3 && scheduler->live == 3 && actors->player == 1);
    CHECK(pe_actors_collect(actors));
    CHECK(actors->live == 2 && scheduler->live == 2 && actors->player == -1);
    CHECK(banks.move_lock == 0xfffffff2 && !(actors->slots[0].script.flags & 0x800000));
    CHECK(actors->slots[0].next == 2 && actors->slots[2].previous == 0);
    CHECK(pe_actors_spawn(actors, 1, 4, 0, 1, 2, 3) == 1);
    CHECK(actors->slots[1].script.field_id == 4 && scheduler->slots[1].task.actor == &actors->slots[1].script);
    for (unsigned i = 0; i < 3; ++i) actors->slots[i].script.flags |= 0x10;
    CHECK(pe_actors_collect(actors));
    CHECK(!actors->live && !scheduler->live && actors->head == -1);
    CHECK(pe_actors_collect(actors));
    int lonely = pe_actors_spawn(actors, 1, 0, -1, 0, 0, 0); CHECK(lonely >= 0);
    actors->slots[lonely].next = lonely;
    CHECK(!pe_actors_collect(actors) && actors->live == 1 && scheduler->live == 1);
    actors->slots[lonely].next = -1; actors->slots[lonely].script.flags |= 0x10;
    CHECK(pe_actors_collect(actors) && !actors->live && !scheduler->live);
