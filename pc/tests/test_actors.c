#include <stdlib.h>
#define CHECK(x) do { if (!(x)) { fprintf(stderr, "line %d: %s\n", __LINE__, #x); exit(1); } } while (0)
static void word(uint8_t *p, uint32_t v) { for (unsigned i=0; i<4; ++i) p[i]=(uint8_t)(v>>(i*8)); }
