@dataclass
class OverlayResult:
    name: str
    error: str | None = None
    base_identical: bool = False
    sections_moved: bool = False
    comparison: Comparison = field(default_factory=Comparison)
    highest_reference: int = 0  # highest retail block address the overlay links to
    literal_code_words: list = field(default_factory=list)  # (address, value, where)


def overlay_link(name: str, main_elf: Path, out: Path) -> tuple[Path | None, str | None]:
    """Generate link_symbols against MAIN_ELF and link with --emit-relocs."""
    build_dir = BUILD / "overlays" / name
    ld_script = LINKERS / "overlays" / f"{name}.ld"
    out.mkdir(parents=True, exist_ok=True)
    symbols = out / f"link_symbols.{name}.txt"
    cmd = [PY, "tools/scripts/overlay_link_symbols.py", str(build_dir.relative_to(ROOT)),
           "--ld", str(ld_script.relative_to(ROOT)), "--out", str(symbols),
           "--config", str((OVERLAY_CONFIGS / f"{name}.yaml").relative_to(ROOT)),
           "--configs", str(OVERLAY_CONFIGS.relative_to(ROOT)),
           "--main-elf", str(main_elf), "--abi", "linkers/USA/overlay_abi.txt",
           "--catalogue", f"linkers/USA/overlays/undefined_funcs_auto.{name}.txt",
           "--catalogue", f"linkers/USA/overlays/undefined_syms_auto.{name}.txt",
           "--catalogue", f"configs/USA/overlays/sym.{name}.txt"]
    if name in PIN_DEFINED_OVERLAYS:
        cmd.append("--pin-defined")
    res = run(cmd)
    if res.returncode:
        return None, f"link_symbols: {res.stderr.strip()[-800:]}"
    elf = out / f"{name}.elf"
    cmd = [st.LD, "-EL", "-q"]
    if name in PIN_DEFINED_OVERLAYS:
        cmd.append("--no-check-sections")
    cmd += ["-T", str(ld_script), "-T", str(symbols), "-Map", str(out / f"{name}.map"), "-o", str(elf)]
    res = run(cmd)
    if res.returncode:
        return None, f"link: {res.stderr.strip()[-800:]}"
    return elf, None


def highest_block_reference(symbols_file: Path, table: overlay_windows.WindowTable) -> int:
    """Highest retail address inside the block that the overlay links to."""
    from tools.scripts.shift_audit import parse_assignments

    highest = 0
    for a in parse_assignments(symbols_file.read_text()):
        value = a.value if a.value is not None else table.evaluate(a.rhs)
        if value is not None and table.contains(value) and not a.name.startswith("OVERLAY_WINDOW_"):
            highest = max(highest, value)
    return highest


def check_overlay(name: str, base_main: Path, shifted_main: Path, pad: int, scratch: Path,
                  table: overlay_windows.WindowTable) -> OverlayResult:
    result = OverlayResult(name)
    built = BUILD / "overlays" / name / f"{name}.bin"
    if not built.exists() or not (LINKERS / "overlays" / f"{name}.ld").exists():
        result.error = "not built (make overlay-build-all)"
        return result
    base_elf, err = overlay_link(name, base_main, scratch / "base" / name)
    if err:
        result.error = "base " + err
        return result
    shifted_elf, err = overlay_link(name, shifted_main, scratch / "shifted" / name)
    if err:
        result.error = "shifted " + err
        return result
    base_bin = objcopy(base_elf, base_elf.with_suffix(".bin"))
    shifted_bin = objcopy(shifted_elf, shifted_elf.with_suffix(".bin"))
    result.base_identical = base_bin == built.read_bytes()
    relocs, base_sections = file_relocations(base_elf)
    _, shifted_sections = file_relocations(shifted_elf)
    result.sections_moved = (
        [n for n, _ in base_sections] == [n for n, _ in shifted_sections]
        and all(vs - vb == pad for (_, vb), (_, vs) in zip(base_sections, shifted_sections)))
    compare_words(base_bin, shifted_bin, relocs, pad, result.comparison, name)
    result.highest_reference = highest_block_reference(
        scratch / "base" / name / f"link_symbols.{name}.txt", table)
    result.literal_code_words = literal_code_words(base_elf)
    return result


