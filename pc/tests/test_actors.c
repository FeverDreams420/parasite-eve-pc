    CHECK(pe_actor_find_floor(subject,&collision) && subject->position[1] == 0x12345678);
    subject->script.flags |= 0x80;
    CHECK(!pe_actor_find_floor(subject,&collision) && subject->position[1] == 0x12345678);
    subject->script.flags &= ~UINT32_C(0x80); subject->position[0] = 0x100000;
