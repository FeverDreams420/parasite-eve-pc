/* Font glyph selection (0x80038BC0..0x8003999C): the glyph table lookups, the
 * selection state flags, the shuffled code list and its incremental load, and
 * stepping the selection through the cached glyph slots. All of it reads and
 * writes g_FontSelectionState (main_tu_evidence G0313). */

#include "common.h"
#include "pe1/cdrom.h"
#include "pe1/font.h"
#include <stdlib.h>

/* Resident initial values from the USA executable. */
FontGlyphSelectionState g_FontSelectionState = { .selected = 0xff };
FontGlyphTable g_FontActiveGlyphTable;
unsigned char g_FontGlyphCodeSequence[71];

/* Slot of the first glyph group whose code matches, or 255. */
static inline unsigned char Font_FindCodeSlot(FontGlyphTable *table, unsigned short code)
{
    unsigned char selected;
    int i, count;
    FontGlyphGroups *groups;
    FontGlyphSlots *slots;

    selected = 0;
    i = 0;
    count = table->groups.count;
    groups = &table->groups;
    if (i < count) {
        int limit;
        code &= 255;
        limit = count;
        do {
            if (groups->codes[i] == code) {
                selected = i;
                i = groups->count;
            }
            ++i;
        } while (i < limit);
    }
    slots = (FontGlyphSlots *)(groups + 1);
    for (i = 0; i < slots->count; ++i) {
        if (slots->indices[i] == selected) return i;
    }
    return 255;
}

unsigned char Render_DrawTextDigit(FontGlyphTable *table, unsigned char mode)
{
    unsigned char selected;
    int code;
    int i, count;
    FontGlyphGroups *groups;
    FontGlyphSlots *slots;

    if (!table) table = g_FontSelectionState.table;
    switch (mode) {
    case 0: code = 3; break;
    case 1: code = (unsigned char)((unsigned)g_FontSelectionState.codeIndex % 10) != 0; break;
    case 2: code = 2; break;
    default: code = 4; break;
    }
    selected = 0;
    i = 0;
    count = table->groups.count;
    groups = &table->groups;
    if (i < count) {
        int limit;
        code &= 255;
        limit = count;
        do {
            if (groups->codes[i] == code) {
                selected = i;
                i = groups->count;
            }
            ++i;
        } while (i < limit);
    }
    slots = (FontGlyphSlots *)(groups + 1);
    for (i = 0; i < slots->count; ++i) {
        if (slots->indices[i] == selected) return i;
    }
    return 255;
}

/* Code of the glyph cached in slot `index`. */
int Render_GetFontSlotCode(int index)
{
    FontGlyphTable *table = g_FontSelectionState.table;

    return table->groups.codes[table->slots.indices[(u8)index]];
}

int Menu_IsEquipSlotActive(void) {
    return g_FontSelectionState.active != 0;
}

int Menu_ConsumeEquipSlotFlag(void) {
    u8 *ptr;

    ptr = &g_FontSelectionState.loadFailed;
    if (*ptr != 0) {
        *ptr = 0;
        return 0;
    }

    return 0xFF;
}

int Render_ConsumeFontShuffleSeed(void) {
    u32 *state = &g_FontSelectionState.seed;

    if (*state != 0) {
        *state = 0;
        return 0;
    }

    return 0xFF;
}

static inline int find_slot(u8 *table)
{
    int found = 0;
    int k;
    u8 *groups = table + 1;
    u8 *slots;
    u8 *entry;
    unsigned int count_offset;

    /* Retain the separate loop-bound reload generated by stock GCC. */
    count_offset = 3;
    for (k = 0; k < table[count_offset]; k++) {
        entry = groups + k;
        if (entry[3] == 2) {
            found = k;
            k = groups[2];
        }
    }
    slots = groups + 0x1B;
    for (k = 0; k < groups[0x1B]; k++) {
        entry = slots + k;
        if (entry[1] == (found & 255)) {
            return k;
        }
    }
    return 255;
}

/* A failed poll restarts the load through a tail call, as in
 * Render_LoadFontGlyph. GCC 2.7 only turns it into a jump when the return
 * type is int (a u8 result is converted at the return). */
int Render_LoadFontGlyphAlt(void)
{
    u16 *range;
    Pe1GameState *state;
    int read_status;
    int poll_status;
    u8 i;
    int forced_slot;
    s16 unique_count;
    int glyph;
    s16 limit;
    u8 duplicate;
    u8 j;

    state = &g_GameState;
    range = &g_PeImageSectorTable[79];
    do {
        read_status = CdRom_ReadSectorsFromLba(state->pe_image_base_lba + range[0],
                                             state->scene_load_scratch,
                                             range[1] - range[0]);
    } while (read_status == -1);

    for (;;) {
        poll_status = CdRom_PollReady();
        if (poll_status == 0) {
            break;
        }
        if (poll_status == -1) {
            return Render_LoadFontGlyphAlt();
        }
    }

    g_FontActiveGlyphTable.codeCount = g_SceneLoadScratchBuffer[0][0];
    if (g_FontSelectionState.loadFailed == 0 && g_FontSelectionState.seed == 0) {
        do {
            g_FontSelectionState.seed = rand() % 0x7FFF;
        } while (g_FontSelectionState.seed == 0);
    }

    /* The identical arms retain the stock compiler's branch-delay scheduling. */
    if (g_FontSelectionState.loadFailed) {
        srand(g_FontSelectionState.seed);
    } else {
        srand(g_FontSelectionState.seed);
    }

    unique_count = 0;
    forced_slot = 0;
    for (i = 0; i < 0x45; i++) {
        if ((i + 2) % 10 == 0) {
            (g_FontGlyphCodeSequence + 2)[i] = forced_slot;
            forced_slot++;
            continue;
        }

        if (i + 2 < 10) {
            limit = 0x68;
        } else if (i + 2 < 20) {
            limit = 0x6D;
        } else {
            limit = 0x71;
        }

        if (g_FontActiveGlyphTable.codeCount - 1 < limit) {
            limit = g_FontActiveGlyphTable.codeCount;
            limit = limit - 1;
        }

        glyph = (rand() % (limit - 7)) + 7;
        (g_FontGlyphCodeSequence + 2)[i] = glyph;

        if (unique_count < g_FontActiveGlyphTable.codeCount - 9) {
            do {
                duplicate = 1;
                for (j = 0; j < i; j++) {
                    if ((g_FontGlyphCodeSequence + 2)[j] == (g_FontGlyphCodeSequence + 2)[i]) {
                        (g_FontGlyphCodeSequence + 2)[i] = (rand() % (limit - 7)) + 7;
                        duplicate = 0;
                    }
                }
            } while (duplicate == 0);
        }
        unique_count++;
    }

    Render_LoadFontGlyph((g_FontGlyphCodeSequence + 2)[0]);

    g_FontSelectionState.active = 1;
    g_FontSelectionState.codeIndex = 2;
    g_FontSelectionState.code = (g_FontGlyphCodeSequence + 2)[0];
    g_FontSelectionState.table = &g_FontActiveGlyphTable;

    g_FontSelectionState.selected = find_slot((u8 *)&g_FontActiveGlyphTable);
    {
        FontGlyphTable *table = g_FontSelectionState.table;
        /* Read back through a pointer: CSE would otherwise reuse the stored
         * slot instead of reloading it as retail does. */
        return table->groups.codes[table->slots.indices[*(u8 *)&g_FontSelectionState.selected]];
    }
}


u8 Render_StepFontLoad(void) {
    u8 state;
    u8 next;
    u8 code;
    FontGlyphTable *result;
    u16 digit;
    u8 *statep;

    statep = &g_FontSelectionState.codeIndex;
    state = *statep;
    if (state < 3U) {
        *statep = 1;
        return 0xFFU;
    }

    next = state - 1;
    *statep = next;
    code = g_FontGlyphCodeSequence[next];
    g_FontSelectionState.code = code;
    Render_LoadFontGlyph(code);

    digit = (u8)(g_FontSelectionState.codeIndex % 10) != 0;
    g_FontSelectionState.selected = Font_FindCodeSlot(g_FontSelectionState.table, digit);
    result = g_FontSelectionState.table;
    return result->groups.codes[result->slots.indices[g_FontSelectionState.selected]];
}

int Menu_GetEquipSlotStateOrIndex(void) {
    if (g_FontSelectionState.active == 0) {
        return 1;
    }

    return g_FontSelectionState.codeIndex;
}

u8 Render_FindFontGlyphSlot(void) {
    u8 index;
    u8 code;
    FontGlyphTable *result;

    if (g_FontSelectionState.codeIndex >= 0x46U) {
        g_FontSelectionState.loadFailed = 1;
        return 0xFFU;
    }
    index = g_FontSelectionState.codeIndex + 1;
    g_FontSelectionState.codeIndex = index;
    code = g_FontGlyphCodeSequence[index];
    g_FontSelectionState.loadFailed = 0;
    g_FontSelectionState.code = code;
    Render_LoadFontGlyph(code);
    g_FontSelectionState.selected = Font_FindCodeSlot(g_FontSelectionState.table, 2);
    result = g_FontSelectionState.table;
    return result->groups.codes[result->slots.indices[g_FontSelectionState.selected]];
}

static inline int findSlot(int useDecimalGroup)
{
    unsigned char code;
    int i, count;
    int found;
    FontGlyphGroups *groups;
    FontGlyphSlots *slots;
    FontGlyphTable *table;

    code = useDecimalGroup ? (unsigned char)((unsigned)g_FontSelectionState.codeIndex % 10) != 0 : 3;
    found = 0;
    table = g_FontSelectionState.table;
    i = 0;
    count = table->groups.count;
    groups = &table->groups;
    for (; i < count; ++i) {
        if (groups->codes[i] == code) {
            found = i;
            i = groups->count;
        }
    }
    slots = (FontGlyphSlots *)(groups + 1);
    for (i = 0; i < slots->count; ++i) {
        if (slots->indices[i] == (unsigned char)found)
            return i;
    }
    return 255;
}

unsigned char Render_SetFontGlyphByCode(unsigned char code)
{
    int selected;
    if ((int)code - 2 >= 69) {
        g_FontSelectionState.loadFailed = 1;
        return 255;
    }
    if (code < 2) {
        g_FontSelectionState.codeIndex = 1;
        return 255;
    }
    g_FontSelectionState.codeIndex = code;
    code = g_FontGlyphCodeSequence[code];
    g_FontSelectionState.code = code;
    Render_LoadFontGlyph(code);
    if (g_FontSelectionState.loadFailed == 1)
        selected = findSlot(1);
    else
        selected = findSlot(0);
    g_FontSelectionState.selected = selected;
    /* Keep retail's store and reload of the selected byte. */
    {
        FontGlyphTable *table = g_FontSelectionState.table;
        int index = g_FontSelectionState.selected;
        g_FontSelectionState.loadFailed = 0;
        return table->groups.codes[table->slots.indices[index]];
    }
}

int Render_GetOrLoadFontGlyph(unsigned char action)
{
    unsigned char code, group;
    int i;
    FontGlyphSlots *slots;
    FontGlyphTable *table = g_FontSelectionState.table;
    code = table->groups.codes[table->slots.indices[g_FontSelectionState.selected]];
    if (code < 2 || code == 24 || code == 31 || code == 38 ||
        code == 45 || code == 52 || code == 59) {
        if (action == 20)
            return Render_FindFontGlyphSlot();
    }
    if (code == 2 && action == 22)
        return Render_StepFontLoad();
    slots = &g_FontSelectionState.table->slots;
    switch (action) {
    case 20:
        group = slots->groupKeys[g_FontSelectionState.selected];
        for (i = g_FontSelectionState.selected - 1; i >= 0; --i) {
            if (slots->groupKeys[i] == group) {
                g_FontSelectionState.selected = i;
                i = 0;
            }
        }
        break;
    case 21:
        --g_FontSelectionState.selected;
        break;
    case 22:
        group = slots->groupKeys[g_FontSelectionState.selected];
        for (i = g_FontSelectionState.selected + 1; i < slots->count; ++i) {
            if (slots->groupKeys[i] == group) {
                g_FontSelectionState.selected = i;
                i = slots->count;
            }
        }
        break;
    case 23:
        ++g_FontSelectionState.selected;
        break;
    }
    {
        FontGlyphTable *last = g_FontSelectionState.table;
        return last->groups.codes[last->slots.indices[g_FontSelectionState.selected]];
    }
}

int Menu_FindSelectedEquipSlotItem(void) {
    FontGlyphTable *result;

    g_FontSelectionState.selected = Font_FindCodeSlot(g_FontSelectionState.table, 3);
    result = g_FontSelectionState.table;
    return result->groups.codes[result->slots.indices[g_FontSelectionState.selected]];
}

int Menu_ResetEquipSlotState(void) {
    g_FontSelectionState.selected = 0xFF;
    g_FontSelectionState.active = 0;
    g_FontSelectionState.code = 0;
    g_FontSelectionState.table = 0;
    return 0;
}
