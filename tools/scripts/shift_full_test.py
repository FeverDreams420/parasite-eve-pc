# room


def startup_stack_bottom(elf: Path) -> int | None:
    """0x80000000 | (_ramsize - 8) - _stacksize, as __SN_ENTRY_POINT computes it."""
    from elftools.elf.elffile import ELFFile

    with open(elf, "rb") as fh:
        e = ELFFile(fh)
        syms = {s.name: s["st_value"] for s in e.get_section_by_name(".symtab").iter_symbols()
                if s.name in ("_ramsize", "_stacksize")}
        if len(syms) != 2:
            return None
        values = {}
        for name, addr in syms.items():
            for sec in e.iter_sections():
                if sec["sh_type"] == "SHT_PROGBITS" and sec["sh_addr"] <= addr < sec["sh_addr"] + sec["sh_size"]:
                    off = addr - sec["sh_addr"]
                    values[name] = int.from_bytes(sec.data()[off:off + 4], "little")
    if len(values) != 2:
        return None
    return (0x80000000 | (values["_ramsize"] - 8)) - values["_stacksize"]


def main_highest_block_reference(elf: Path, table: overlay_windows.WindowTable) -> int:
    """Highest retail block address a relocation in main points at."""
    base = st.load_image(elf)
    values = [rel[2] for rel in base.relocs.values() if table.contains(rel[2])]
    return max(values, default=0)


