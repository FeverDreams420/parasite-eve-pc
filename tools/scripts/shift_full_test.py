#!/usr/bin/env python3
"""Full shifted build: main and every overlay, compared with the retail build.

Needs `make build` and `make overlay-build-all`. Everything is linked into a
scratch directory; the repository is never written.

1. Main is relinked from the built objects with --emit-relocs twice: as is
   (it must equal build/USA/main.exe) and with PAD bytes inserted at the
   start of `.main` (shift_test.pad_script). Nothing in the linker script
   is placed at a fixed address, so the field engine, the boot work area
   and the whole overlay window block move by PAD.
2. Every overlay is relinked twice from its built objects with
   --emit-relocs, each time with a link_symbols script freshly generated by
   overlay_link_symbols.py: against the base main (it must equal the built
   overlay binary) and against the shifted main, whose window symbols put
   every overlay segment PAD bytes higher.
3. The images are compared word by word. A word that differs must carry a
   relocation whose field changed by exactly PAD (a 32-bit word, a j/jal
   target, a hi/lo half). Nothing else may differ. The PS-X EXE header may
   differ only in its initial PC (the startup moves with main) and its text
   size, both by PAD; an entry point that did not move is a failure, since
   the BIOS would jump into the middle of other code.

Words that did not change although their relocation points into the program
(main's remaining absolute pins, see shift_test.py) are listed too: they
would point at the wrong bytes after a real shift. They are main's debt, not
a difference between the images.

The report ends with the room the layout has: how far the image can grow
before it reaches the initial stack pointer (the link fails beyond that,
tools/scripts/ld_postpass.py), and how far the memory that code refers to
inside the window block can move before it reaches the stack area the
startup reserves.
"""
