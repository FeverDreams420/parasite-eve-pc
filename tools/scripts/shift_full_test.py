@dataclass
class MainLinks:
    base_elf: Path
    shifted_elf: Path
    base_identical: bool
    pinned: list[str]
    comparison: Comparison


def link_main(pad: int, scratch: Path) -> MainLinks:
    script = LINKERS / "main.ld"
    extra = [LINKERS / "undefined_syms_manual.txt", LINKERS / "undefined_addr_aliases.main.txt"]
    for need in [script, *extra, BUILD / "main.exe", BUILD / "main.map"]:
        if not need.exists():
            sys.exit(f"missing {need}: run `make build` first")
    base_elf = scratch / "main.base.elf"
    res = st.link(script, base_elf, extra)
    if res.returncode:
        sys.exit("base main link failed:\n" + res.stderr)
    base_exe = objcopy(base_elf, scratch / "main.base.exe")
    shifted_script, pinned = st.pad_script(script.read_text(), pad, rebase=False)
    (scratch / "main.shifted.ld").write_text(shifted_script)
    shifted_elf = scratch / "main.shifted.elf"
    res = st.link(scratch / "main.shifted.ld", shifted_elf, extra)
    if res.returncode:
        sys.exit("shifted main link failed (no fixed placement may block it):\n" + res.stderr[-3000:])
    shifted_exe = objcopy(shifted_elf, scratch / "main.shifted.exe")

    result = Comparison()
    compare_header(base_exe, shifted_exe, pad, result)
    base = st.load_image(base_elf)
    shifted = st.load_image(shifted_elf)
    layout = Layout(parse_map_sections((scratch / "main.base.map").read_text()))
    counts, findings = st.compare(base, shifted, pad, layout)
    # shift_test's kinds: pinned words and literals did not move.
    for kind, n in counts.items():
        mapped = DID_NOT_MOVE if kind in ("pinned_symbol_reference", "gprel_to_pinned",
                                          "relocated_unchanged_other") else kind
        result.counts[mapped] += n
        for a, sym, obj, info in findings.get(kind, []):
            result.findings.setdefault(mapped, []).append((a, f"main {sym} {info}"))
    if len(shifted_exe) - len(base_exe) != pad:
        result.add("size_changed", 0, f"main: {len(base_exe):#x} -> {len(shifted_exe):#x} bytes")
    return MainLinks(base_elf, shifted_elf, base_exe == (BUILD / "main.exe").read_bytes(),
                     pinned, result)


