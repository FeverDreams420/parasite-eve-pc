    PeMatrix base;pe_matrix_identity(&base);base.translation[0]=100;
    CHECK(pe_actor_model_pose(subject,&base));
    CHECK(subject->render->pose_count==1&&subject->render->pose[0].translation[0]==107);
    CHECK(subject->render->volume_count==1&&subject->render->volumes[0].center[0]==107&&subject->render->body[3]==42);
