    uint8_t bytes[64] = {0}; word(bytes + 8, 32); word(bytes + 12, 32); word(bytes + 32, 32);
    PeRoomBlob blob = {0}; blob.bytes = bytes; blob.size = sizeof(bytes);
    PeScriptProgram program = {0}; program.blob = &blob; program.entries = 2;
