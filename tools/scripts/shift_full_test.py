def measure(pad: int, scratch: Path, names: list[str], jobs: int) -> dict:
    table = overlay_windows.load()
    main = link_main(pad, scratch)
    syms = elf_symbols(main.base_elf)
    shifted_syms = elf_symbols(main.shifted_elf)
    results: list[OverlayResult] = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=jobs) as pool:
        futures = [pool.submit(check_overlay, n, main.base_elf, main.shifted_elf, pad, scratch, table)
                   for n in names]
        results = [f.result() for f in futures]
    overlay_counts = Counter()
    findings: dict[str, list] = {}
    for r in results:
        overlay_counts.update(r.comparison.counts)
        for kind, items in r.comparison.findings.items():
            findings.setdefault(kind, []).extend(items)
    highest = max([main_highest_block_reference(main.base_elf, table)]
                  + [r.highest_reference for r in results])
    stack_bottom = startup_stack_bottom(main.base_elf)
    windows_moved = all(shifted_syms[w] - syms[w] == pad for w in table.symbols)
    return {
        "pad": pad,
        "main": {
            "base_identical": main.base_identical,
            "fixed_placements": main.pinned,
            "counts": dict(main.comparison.counts),
            "findings": {k: v[:50] for k, v in main.comparison.findings.items()},
        },
        "overlays": {
            "checked": len(results),
            "errors": {r.name: r.error for r in results if r.error},
            "not_identical": [r.name for r in results if not r.error and not r.base_identical],
            "sections_not_moved": [r.name for r in results if not r.error and not r.sections_moved],
            "counts": dict(overlay_counts),
            "findings": {k: v[:50] for k, v in findings.items()},
            "literal_code_words": {r.name: [(a, v, w) for a, v, w in r.literal_code_words]
                                   for r in results if r.literal_code_words},
        },
        "windows_moved": windows_moved,
        "block": {
            "base": syms[overlay_windows.BASE_SYMBOL],
            "shifted_base": shifted_syms[overlay_windows.BASE_SYMBOL],
            "image_end": syms["overlay_windows_VRAM_END"],
            "stack_top": syms["PSX_EXE_STACK_TOP"],
            "headroom": syms["PSX_EXE_HEADROOM"],
            "shifted_headroom": shifted_syms["PSX_EXE_HEADROOM"],
            "highest_reference": highest,
            "startup_stack_bottom": stack_bottom,
        },
    }


def passed(report: dict) -> bool:
    main, ovl = report["main"], report["overlays"]
    return (main["base_identical"] and not main["fixed_placements"]
            and not any(main["counts"].get(k) for k in FAILING + ("size_changed",))
            and not ovl["errors"] and not ovl["not_identical"] and not ovl["sections_not_moved"]
            and not any(ovl["counts"].get(k) for k in FAILING + ("size_changed",))
            and report["windows_moved"])


def render(report: dict, verbose: int) -> str:
    out = []
    pad = report["pad"]
    main, ovl, block = report["main"], report["overlays"], report["block"]
    out.append(f"shift by 0x{pad:X}: main base relink identical to build/USA/main.exe: "
               f"{main['base_identical']}; fixed placements: {', '.join(main['fixed_placements']) or 'none'}")
    out.append(f"overlay window block: 0x{block['base']:08X} -> 0x{block['shifted_base']:08X}; "
               f"every window symbol moved by the pad: {report['windows_moved']}")
    out.append(f"overlays relinked: {ovl['checked']}; base relink differs from the built binary: "
               f"{len(ovl['not_identical'])}; link errors: {len(ovl['errors'])}; "
               f"sections that did not move by the pad: {len(ovl['sections_not_moved'])}")
    for name, err in list(ovl["errors"].items())[:verbose or 10]:
        out.append(f"  {name}: {err}")
    for title, counts in (("main (header + image)", main["counts"]), ("overlays", ovl["counts"])):
        out.append(f"\n{title}: compared {sum(counts.values())} words")
        for k, v in sorted(counts.items(), key=lambda kv: -kv[1]):
            out.append(f"  {k:28} {v:8}")
    for title, findings in (("main", main["findings"]), ("overlays", ovl["findings"])):
        for kind, items in sorted(findings.items()):
            out.append(f"\n{title} {kind}: (first {min(len(items), verbose or 10)})")
            for where, info in items[:verbose or 10]:
                out.append(f"  {where:08X} {info}")
    literal = ovl.get("literal_code_words", {})
    if literal:
        out.append(f"\noverlays: {sum(len(v) for v in literal.values())} unrelocated data words hold the "
                   f"address of one of their functions, in {len(literal)} overlays (they keep the retail "
                   f"address in a shifted link; not counted as failures):")
        for name, words in sorted(literal.items(), key=lambda kv: -len(kv[1]))[:verbose or 10]:
            addr, value, where = words[0]
            out.append(f"  {name:28} {len(words):5}  first {addr:08X} = {value:08X} at {where}")
    out.append("")
    out.append(f"image end 0x{block['image_end']:08X}, initial stack pointer 0x{block['stack_top']:08X}: "
               f"main may grow by 0x{block['headroom']:X} bytes before the link fails "
               f"(0x{block['shifted_headroom']:X} left after this shift)")
    if block["startup_stack_bottom"] is not None:
        bottom = block["startup_stack_bottom"]
        high = block["highest_reference"]
        out.append(f"highest block address any object refers to: 0x{high:08X}; the startup's stack "
                   f"area starts at 0x{bottom:08X}: 0x{bottom - high:X} bytes between them")
    out.append("")
    out.append("PASS: every difference is a relocated address field moved by the pad"
               if passed(report) else "FAIL")
    return "\n".join(out)


def overlay_names() -> list[str]:
    return sorted(cfg.stem for cfg in OVERLAY_CONFIGS.glob("*.yaml"))


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--pad", type=lambda s: int(s, 0), default=0x10,
                        help="bytes inserted before main's first unit (multiple of 4, default 0x10)")
    parser.add_argument("--scratch", type=Path, help="keep the scratch links here")
    parser.add_argument("--jobs", type=int, default=8)
    parser.add_argument("--json", action="store_true")
    parser.add_argument("-v", "--verbose", type=int, default=0, help="rows per listing")
    parser.add_argument("overlays", nargs="*", help="overlays to check (default: all configured)")
    args = parser.parse_args(argv)
    if args.pad % 4 or args.pad <= 0:
        parser.error("--pad must be a positive multiple of 4")
    names = args.overlays or overlay_names()

    def go(scratch: Path) -> int:
        report = measure(args.pad, scratch, names, args.jobs)
        print(json.dumps(report, indent=1) if args.json else render(report, args.verbose))
        return 0 if passed(report) else 1

    if args.scratch:
        args.scratch.mkdir(parents=True, exist_ok=True)
        return go(args.scratch)
    with tempfile.TemporaryDirectory(prefix="shift_full_") as tmp:
        return go(Path(tmp))


if __name__ == "__main__":
    sys.exit(main())
