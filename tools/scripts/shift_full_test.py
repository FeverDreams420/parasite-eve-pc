HEADER_SIZE = 0x800
ENTRY_OFFSET = 0x10  # PS-X EXE header: initial PC
TEXT_SIZE_OFFSET = 0x1C  # PS-X EXE header: .text size
PY = sys.executable


@dataclass
class Reloc:
    rtype: int
    symbol: str
    value: int  # the symbol's value in the base link
    absolute: bool


@dataclass
class Comparison:
    counts: Counter = field(default_factory=Counter)
    findings: dict = field(default_factory=dict)  # kind -> [(offset, info)]

    def add(self, kind: str, offset: int | None = None, info: str = "") -> None:
        self.counts[kind] += 1
        if offset is not None:
            self.findings.setdefault(kind, []).append((offset, info))


# Kinds that make the test fail: a difference no relocation explains.
FAILING = ("unexplained_relocated", "unexplained_difference", "missing_in_shifted")
# Relocated words into the program that did not move (main's pins).
DID_NOT_MOVE = "did_not_move"


def compare_words(base: bytes, shifted: bytes, relocs: dict[int, Reloc], pad: int,
                  result: Comparison | None = None, label: str = "") -> Comparison:
    """Compare two images of the same layout at the same offsets (an overlay:
    its file offsets do not move, its addresses do)."""
    result = result or Comparison()
    if len(base) != len(shifted):
        result.add("size_changed", 0, f"{label}: {len(base):#x} -> {len(shifted):#x} bytes")
    for off in range(0, len(base) - 3, 4):
        if off + 4 > len(shifted):
            result.add("missing_in_shifted", off, label)
            continue
        wb = int.from_bytes(base[off:off + 4], "little")
        ws = int.from_bytes(shifted[off:off + 4], "little")
        classify_word(off, wb, ws, relocs.get(off), pad, result, label)
    return result


def classify_word(where: int, wb: int, ws: int, rel: Reloc | None, pad: int,
                  result: Comparison, label: str = "") -> None:
    if rel is None:
        if wb == ws:
            result.counts["unchanged"] += 1
        else:
            result.add("unexplained_difference", where, f"{label} {wb:08X}->{ws:08X}")
        return
    fixed = address_region(rel.value) is not None
    if wb == ws:
        if rel.rtype == st.R_MIPS_GPREL16:
            result.counts["gprel_unchanged"] += 1
        elif fixed:
            result.counts["hardware_reference"] += 1
        elif rel.rtype == st.R_MIPS_HI16:
            result.counts["unchanged_half"] += 1  # no carry into the upper half
        else:
            result.add(DID_NOT_MOVE, where, f"{label} {rel.symbol}")
    elif rel.rtype == st.R_MIPS_GPREL16:
        result.add("unexplained_relocated", where, f"{label} gp-relative {rel.symbol}")
    elif st.explained(rel.rtype, wb, ws, pad):
        result.counts["shifted_address_field"] += 1
    else:
        result.add("unexplained_relocated", where,
                   f"{label} type {rel.rtype} {rel.symbol} {wb:08X}->{ws:08X}")


def compare_header(base: bytes, shifted: bytes, pad: int, result: Comparison) -> None:
    """Only the initial PC (the startup, which lies after the pad) and the
    text size may change, and by exactly PAD."""
    for off in range(0, HEADER_SIZE, 4):
        wb = int.from_bytes(base[off:off + 4], "little")
        ws = int.from_bytes(shifted[off:off + 4], "little")
        if wb == ws:
            continue
        if off == TEXT_SIZE_OFFSET and ws - wb == pad:
            result.counts["header_text_size"] += 1
        elif off == ENTRY_OFFSET and ws - wb == pad:
            result.counts["header_entry_point"] += 1
        else:
            result.add("unexplained_difference", off, f"header word {off:#x} {wb:08X}->{ws:08X}")
    if pad and base[ENTRY_OFFSET:ENTRY_OFFSET + 4] == shifted[ENTRY_OFFSET:ENTRY_OFFSET + 4]:
        result.add("unexplained_difference", ENTRY_OFFSET, "header initial PC did not move with the startup")


